def p(text, style=BODY):
    return Paragraph(text, style)


def bullets(items):
    return [p(f"<bullet>&bull;</bullet>{item}", BODY) for item in items]


def numbered(items):
    return [p(f"<b>{index}.</b> {item}", BODY) for index, item in enumerate(items, 1)]


def figure(name, caption, max_width=176 * mm, max_height=105 * mm):
    image = Image(str(IMAGE_DIR / name))
    scale = min(max_width / image.imageWidth, max_height / image.imageHeight)
    image.drawWidth = image.imageWidth * scale
    image.drawHeight = image.imageHeight * scale
    image.hAlign = "CENTER"
    return [image, Spacer(1, 2 * mm), p(caption, CAP), Spacer(1, 4 * mm)]


def callout(title, text, color=PALE):
    table = Table([[p(title, BUTTON), p(text, BODY)]], colWidths=[34 * mm, 142 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), color), ("BOX", (0, 0), (-1, -1), 0.5, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7), ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return table


def button_table(rows, widths=(55, 121)):
    data = [[p("Кнопка / поле", BUTTON), p("Что делает", BUTTON)]]
    data += [[p(a, BUTTON), p(b, SMALL)] for a, b in rows]
    table = Table(data, colWidths=[widths[0] * mm, widths[1] * mm], repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), GREEN), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.35, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND", (0, 1), (-1, -1), colors.white),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, PAPER]),
        ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table


def footer(canvas, doc):
    canvas.saveState()
    canvas.setFillColor(GREEN)
    canvas.rect(0, A4[1] - 9 * mm, A4[0], 9 * mm, fill=1, stroke=0)
    canvas.setFont("DV-Bold", 7.5)
    canvas.setFillColor(colors.white)
    canvas.drawString(17 * mm, A4[1] - 6 * mm, "DroneVision - краткая инструкция")
    canvas.setStrokeColor(LINE)
    canvas.line(17 * mm, 13 * mm, A4[0] - 17 * mm, 13 * mm)
    canvas.setFillColor(MUTED)
    canvas.setFont("DV", 7)
    canvas.drawString(17 * mm, 8.5 * mm, "Локальная обработка: видео и телеметрия не отправляются в интернет")
    canvas.drawRightString(A4[0] - 17 * mm, 8.5 * mm, f"{doc.page}")
    canvas.restoreState()


